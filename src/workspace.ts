import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

/**
 * Source of the app.config.js written into the temp copy. It hands Expo's
 * config to the bundled runtime, which picks the plugins for the current step.
 */
export function wrapperConfigSource(runtimePath = require.resolve('./runtime/app-config.cjs')): string {
  return `// Generated by prebuild-blame. Safe to delete.\nmodule.exports = require(${JSON.stringify(runtimePath)});\n`;
}
