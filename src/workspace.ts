import { cpSync, existsSync, mkdirSync, mkdtempSync, renameSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';
import path from 'node:path';
import type { ExpoProject } from './expo.js';
import { WORKSPACE_FILE, type WorkspaceInfo } from './steps.js';

// Never copied: generated output and caches at the top level, and dependencies
// (symlinked instead) and git data anywhere.
const SKIP_TOP = new Set(['android', 'ios', '.expo', 'dist', 'web-build']);
const SKIP_ANY = new Set(['node_modules', '.git']);

/**
 * Source of the app.config.js written into the temp copy. It hands Expo's
 * config to the bundled runtime, which picks the plugins for the current step.
 */
export function wrapperConfigSource(runtimePath = findRuntime()): string {
  return `// Generated by prebuild-blame. Safe to delete.\nmodule.exports = require(${JSON.stringify(runtimePath)});\n`;
}

// Next to the built CLI in dist/, or in dist/ when running from source (tests).
function findRuntime(): string {
  for (const candidate of ['./runtime/app-config.cjs', '../dist/runtime/app-config.cjs']) {
    const file = fileURLToPath(new URL(candidate, import.meta.url));
    if (existsSync(file)) return file;
  }
  throw new Error('prebuild-blame runtime not found. Run `npm run build` first.');
}

export interface Workspace {
  root: string;
  /** A fresh copy of the project for one step. */
  stepDir(step: number): string;
  dispose(): void;
}

/** Prepares a template copy of the project that each step is cloned from. */
export function createWorkspace(project: ExpoProject): Workspace {
  const root = mkdtempSync(path.join(tmpdir(), 'prebuild-blame-'));
  const template = path.join(root, 'project');

  cpSync(project.root, template, {
    recursive: true,
    filter: (src) => {
      const rel = path.relative(project.root, src);
      const parts = rel.split(path.sep);
      return rel === '' || (!SKIP_TOP.has(parts[0]!) && !parts.some((part) => SKIP_ANY.has(part)));
    },
  });

  let userConfig: string | null = null;
  if (project.dynamicConfigPath) {
    userConfig = `prebuild-blame.user-config${path.extname(project.dynamicConfigPath)}`;
    renameSync(path.join(template, path.relative(project.root, project.dynamicConfigPath)), path.join(template, userConfig));
  }
  const info: WorkspaceInfo = { userConfig, autoPlugins: project.autoPlugins };
  writeFileSync(path.join(template, WORKSPACE_FILE), JSON.stringify(info, null, 2));
  writeFileSync(path.join(template, 'app.config.js'), wrapperConfigSource());

  return {
    root,
    stepDir(step) {
      const dir = path.join(root, `step-${step}`);
      mkdirSync(dir);
      cpSync(template, dir, { recursive: true });
      symlinkSync(path.join(project.root, 'node_modules'), path.join(dir, 'node_modules'), 'junction');
      return dir;
    },
    dispose() {
      rmSync(root, { recursive: true, force: true });
    },
  };
}
